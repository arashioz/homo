export function normalizeCategory(name: string): string {
  const trimmed = name.trim();
  if (!trimmed) return "سایر";
  if (CATEGORY_ALIASES[trimmed]) return CATEGORY_ALIASES[trimmed];
  if ((CATALOG_CATEGORIES as readonly string[]).includes(trimmed)) return trimmed;
  return trimmed;
}

export function sortCategoriesBySitePriority<T extends { name: string; count: number }>(
  cats: T[],
): T[] {
  return [...cats].sort((a, b) => {
    const ia = SITE_CATEGORY_PRIORITY.indexOf(a.name);
    const ib = SITE_CATEGORY_PRIORITY.indexOf(b.name);
    const ra = ia < 0 ? 1000 + a.name.localeCompare(b.name, "fa") : ia;
    const rb = ib < 0 ? 1000 + b.name.localeCompare(a.name, "fa") : ib;
    if (ra !== rb) return ra - rb;
    return b.count - a.count;
  });
}

/** Category options for admin selects (canonical + any extras already in catalog) */
export function categoryOptions(existing: string[]): string[] {
  const set = new Set<string>([...CATALOG_CATEGORIES, ...existing.map(normalizeCategory)]);
  return [...set].sort((a, b) => {
    const ia = CATALOG_CATEGORIES.indexOf(a as CatalogCategory);
    const ib = CATALOG_CATEGORIES.indexOf(b as CatalogCategory);
    if (ia >= 0 && ib >= 0) return ia - ib;
    if (ia >= 0) return -1;
    if (ib >= 0) return 1;
    return a.localeCompare(b, "fa");
  });
}
